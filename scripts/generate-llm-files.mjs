#!/usr/bin/env node
/** Generate deterministic article mirrors and indexes from canonical JSON records. */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, unlinkSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (path) => JSON.parse(readFileSync(join(ROOT, path), 'utf8'));
const HEADER_START = '# BEGIN generated article and AI file headers';
const HEADER_END = '# END generated article and AI file headers';
const GENERATED_MARKER = '<!-- Generated by scripts/generate-llm-files.mjs; edit src/content/blog-posts.json instead. -->';

export function validatePosts(posts) {
  if (!Array.isArray(posts) || posts.length === 0) throw new Error('Article registry is empty');
  const slugs = new Set();
  for (const post of posts) {
    for (const field of ['slug', 'title', 'metaDescription', 'category', 'publishDate', 'readingTime', 'content', 'excerpt', 'featuredGradient']) {
      if (typeof post[field] !== 'string' || !post[field].trim()) throw new Error(`Missing article ${field}: ${post.slug || '(unknown)'}`);
    }
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(post.slug)) throw new Error(`Invalid article slug: ${post.slug}`);
    if (slugs.has(post.slug)) throw new Error(`Duplicate article slug: ${post.slug}`);
    slugs.add(post.slug);
    if (!post.author?.name || !Array.isArray(post.headings) || !post.headings.length || !Array.isArray(post.relatedSlugs)) throw new Error(`Incomplete article: ${post.slug}`);
    for (const date of [post.publishDate, post.modifiedDate].filter((value) => value !== undefined)) {
      if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || Number.isNaN(Date.parse(date)) || new Date(date).toISOString().slice(0, 10) !== date) throw new Error(`Invalid article date: ${post.slug}`);
    }
    if (post.modifiedDate && post.modifiedDate < post.publishDate) throw new Error(`Modification predates publication: ${post.slug}`);
  }
  for (const post of posts) {
    for (const related of post.relatedSlugs) {
      if (!slugs.has(related)) throw new Error(`Missing related article: ${post.slug} -> ${related}`);
    }
  }
}

export function summarizePosts(posts) {
  return posts.map((post) => ({
    slug: post.slug, title: post.title, category: post.category, author: post.author.name,
    date: post.publishDate, excerpt: post.excerpt, gradient: post.featuredGradient,
  }));
}

export function htmlToMarkdown(html, siteUrl = "https://rangeljanitorial.com") {
  let md = html;
  // Strip class/id attributes to simplify regex
  md = md.replace(/\sclass="[^"]*"/g, "");
  md = md.replace(/\sid="[^"]*"/g, "");
  // Headings
  md = md.replace(/<h1[^>]*>([\s\S]*?)<\/h1>/g, "\n# $1\n");
  md = md.replace(/<h2[^>]*>([\s\S]*?)<\/h2>/g, "\n## $1\n");
  md = md.replace(/<h3[^>]*>([\s\S]*?)<\/h3>/g, "\n### $1\n");
  md = md.replace(/<h4[^>]*>([\s\S]*?)<\/h4>/g, "\n#### $1\n");
  // Links
  md = md.replace(
    /<a[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/g,
    (_, href, text) => {
      const abs = href.startsWith("http") ? href : `${siteUrl}${href}`;
      return `[${text.trim()}](${abs})`;
    }
  );
  // Paragraphs
  md = md.replace(/<p[^>]*>([\s\S]*?)<\/p>/g, "\n$1\n");
  // Lists
  md = md.replace(/<ul[^>]*>/g, "\n");
  md = md.replace(/<\/ul>/g, "\n");
  md = md.replace(/<ol[^>]*>/g, "\n");
  md = md.replace(/<\/ol>/g, "\n");
  md = md.replace(/<li[^>]*>([\s\S]*?)<\/li>/g, "- $1\n");
  // Strong / em
  md = md.replace(/<(strong|b)[^>]*>([\s\S]*?)<\/\1>/g, "**$2**");
  md = md.replace(/<(em|i)[^>]*>([\s\S]*?)<\/\1>/g, "*$2*");
  // Line breaks
  md = md.replace(/<br\s*\/?>/g, "\n");
  // Strip remaining tags
  md = md.replace(/<[^>]+>/g, "");
  // Entities
  md = md
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&mdash;/g, "—")
    .replace(/&ndash;/g, "–");
  // Collapse whitespace
  md = md.replace(/[ \t]+/g, " ");
  md = md.replace(/^[ \t]+|[ \t]+$/gm, "");
  md = md.replace(/\n{3,}/g, "\n\n");
  return md.trim();
}

export function buildGeneratedFiles({ posts, business, regions, services }) {
  validatePosts(posts);
  const siteUrl = business.url;
  if (!siteUrl || !business.name || !business.email || !Array.isArray(regions) || !regions.length) throw new Error('Incomplete business registry');
  const address = business.headquarters;
  const headquarters = `${address.streetAddress}, ${address.addressLocality}, ${address.addressRegion} ${address.postalCode}`;
  const regionLinks = regions.map((region) => `- [${region.city} — ${region.region}](${siteUrl}/locations/${region.slug}): ${region.phone}`).join('\n');
  const serviceLinks = Object.entries(services).map(([slug, name]) => `- [${name}](${siteUrl}/services/${slug})`).join('\n');
  const files = new Map();
  const description = 'Commercial cleaning and janitorial services for California businesses, with regional teams serving Sacramento, Murrieta and the Inland Empire, and Walnut Creek and the East Bay.';

  for (const post of posts) {
    files.set(`blog/${post.slug}.md`, `${GENERATED_MARKER}
# ${post.title}

> ${post.metaDescription}

**Category:** ${post.category}
**Published:** ${post.publishDate}
${post.modifiedDate ? `**Updated:** ${post.modifiedDate}\n` : ''}**Reading time:** ${post.readingTime}
**Author:** ${post.author.name}
**Source:** ${siteUrl}/blog/${post.slug}

---

${htmlToMarkdown(post.content, siteUrl)}

---

*Published by ${business.name}.*
*Read the original: ${siteUrl}/blog/${post.slug}*
`);
  }

  files.set('llms.txt', `# ${business.name}

> ${description}

## Business information

- **Website:** ${siteUrl}
- **Headquarters:** ${headquarters}
- **Email:** ${business.email}
- **Phones:** ${regions.map((region) => `${region.city} ${region.phone}`).join(' · ')}
- **Office hours:** Contact the regional office to confirm current office hours and cleaning availability.

## Services

${serviceLinks}

## Regional offices and service areas

${regionLinks}

## Cleaning guides

${posts.map((post) => `- [${post.title}](${siteUrl}/blog/${post.slug}): ${post.metaDescription} [Markdown copy](${siteUrl}/blog/${post.slug}.md)`).join('\n')}

## Additional resources

- [Full article text](${siteUrl}/llms-full.txt)
- [Sitemap](${siteUrl}/sitemap.xml)
- [Privacy Policy](${siteUrl}/privacy-policy)
- [Terms of Service](${siteUrl}/terms-of-service)
`);

  // Build time is not a publication or modification date. Omit it so unchanged
  // records produce identical output and do not imply an editorial update.
  files.set('llms-full.txt', `# ${business.name} — Complete Article Content

> ${description}

Source: ${siteUrl}
Publication dates below belong to individual articles. This export does not establish a separate editorial update date.

---

${posts.map((post) => `# ${post.title}

**URL:** ${siteUrl}/blog/${post.slug}
**Category:** ${post.category}
**Published:** ${post.publishDate}
${post.modifiedDate ? `**Updated:** ${post.modifiedDate}\n` : ''}**Author:** ${post.author.name}
**Reading time:** ${post.readingTime}

> ${post.metaDescription}

${htmlToMarkdown(post.content, siteUrl)}

---
`).join('\n')}

## Contact ${business.name}

- **Website:** ${siteUrl}
- **Headquarters:** ${headquarters}
- **Email:** ${business.email}
${regions.map((region) => `- **${region.city}:** ${region.phone}`).join('\n')}
- **Office hours:** Contact the regional office to confirm current office hours and cleaning availability.

${regionLinks}
`);

  const mirrorHeaders = posts.map((post) => `/blog/${post.slug}.md
  Content-Type: text/markdown; charset=utf-8
  Link: <${siteUrl}/blog/${post.slug}>; rel="canonical"
  Cache-Control: public, max-age=3600, must-revalidate`).join('\n\n');
  files.set('_headers', `${HEADER_START}
${mirrorHeaders}

/llms.txt
  Content-Type: text/plain; charset=utf-8
  X-Robots-Tag: noindex, follow
  Cache-Control: public, max-age=3600, must-revalidate

/llms-full.txt
  Content-Type: text/plain; charset=utf-8
  X-Robots-Tag: noindex, follow
  Cache-Control: public, max-age=3600, must-revalidate
${HEADER_END}
`);
  return files;
}

export function writeGeneratedFiles(files, outputDir) {
  mkdirSync(join(outputDir, 'blog'), { recursive: true });
  // Reconcile only this generator's mirrors, never arbitrary files in /blog.
  for (const filename of readdirSync(join(outputDir, 'blog'))) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*\.md$/.test(filename) || files.has(`blog/${filename}`)) continue;
    const path = join(outputDir, 'blog', filename);
    const content = readFileSync(path, 'utf8');
    const legacyGenerated = content.includes('*Published by Rangel Janitorial — ') && content.includes(`*Read the original: https://rangeljanitorial.com/blog/${filename.slice(0, -3)}*`);
    if (content.startsWith(GENERATED_MARKER) || legacyGenerated) unlinkSync(path);
  }
  for (const [relativePath, generated] of files) {
    const path = join(outputDir, relativePath);
    let content = generated;
    if (relativePath === '_headers' && existsSync(path)) {
      const previous = readFileSync(path, 'utf8');
      const start = previous.indexOf(HEADER_START);
      const end = previous.indexOf(HEADER_END);
      if ((start === -1) !== (end === -1) || (start !== -1 && end < start)) throw new Error('Malformed managed _headers block');
      const unmanaged = start === -1 ? previous : previous.slice(0, start) + previous.slice(end + HEADER_END.length);
      content = `${unmanaged.trimEnd()}${unmanaged.trim() ? '\n\n' : ''}${generated}`;
    }
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) writeFileSync(path, content, 'utf8');
  }
}

export function generateLlmFiles() {
  const posts = readJson('src/content/blog-posts.json');
  const business = readJson('src/data/business.json');
  const regions = readJson('src/data/regions.json');
  const services = Object.fromEntries(readJson('src/data/service-index.json').map((service) => [service.slug, service.name]));
  const files = buildGeneratedFiles({ posts, business, regions, services });
  writeGeneratedFiles(files, join(ROOT, 'public'));
  const indexPath = join(ROOT, 'src/content/blog-index.json');
  const index = `${JSON.stringify(summarizePosts(posts), null, 2)}\n`;
  if (!existsSync(indexPath) || readFileSync(indexPath, 'utf8') !== index) writeFileSync(indexPath, index, 'utf8');
  console.log(`[llm-files] Validated ${posts.length} articles; synchronized mirrors, summaries, canonical headers, and business facts.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) generateLlmFiles();
